  function textNodes() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        if (parent.closest('script, style, noscript, textarea, svg, .dealer-lang-switch, .dealer-kz-note')) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });

    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    return nodes;
  }

  function replaceExactText() {
    textNodes().forEach((node) => {
      const value = node.nodeValue;
      const key = value.replace(/\s+/g, ' ').trim();
      const inCatalog = Boolean(node.parentElement?.closest('.product_card, .prdctfltr_filter, .single-product'));
      const cabinetSize = inCatalog && key.match(/^Монтажная тумба ([\d, ]+ см)$/);
      const cutoutSize = inCatalog && key.match(/^вырез (\d+x\d+)\s*мм$/);
      const translated = (inCatalog && catalogOverrides[key]) || exactMap[key] || (inCatalog && catalogMap[key]) ||
        (cabinetSize && `Орнату шкафы ${cabinetSize[1]}`) ||
        (cutoutSize && `ойық ${cutoutSize[1]} мм`);
      if (!key || !translated || translated === key) return;
      textStore.set(node, value);
      const leading = value.match(/^\s*/)[0];
      const trailing = value.match(/\s*$/)[0];
      node.nodeValue = leading + translated + trailing;
    });

    document.querySelectorAll('[aria-label], .product_card [title], .product_card [alt], .prdctfltr_filter [title], .prdctfltr_filter [alt], .single-product [title], .single-product [alt]').forEach((element) => {
      for (const attribute of ['aria-label', 'title', 'alt']) {
        const value = element.getAttribute(attribute);
        if (!value) continue;
        const translated = catalogOverrides[value] || exactMap[value] || catalogMap[value];
        if (!translated || translated === value) continue;
        if (!attributeStore.has(element)) attributeStore.set(element, {});
        if (!(attribute in attributeStore.get(element))) attributeStore.get(element)[attribute] = value;
        element.setAttribute(attribute, translated);
      }
    });

    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach((input) => {
      const original = input.dataset.originalPlaceholder || input.getAttribute('placeholder') || '';
      input.dataset.originalPlaceholder = original;
      input.setAttribute('placeholder', placeholderMap[original] || original);
    });
  }

